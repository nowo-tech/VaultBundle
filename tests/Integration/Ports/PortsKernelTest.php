<?php

declare(strict_types=1);

namespace Nowo\VaultBundle\Tests\Integration\Ports;

use Nowo\VaultBundle\DependencyInjection\Compiler\VaultPortsPass;
use Nowo\VaultBundle\Tests\App\VariantKernel;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;
use Symfony\Bundle\FrameworkBundle\Console\Application;
use Symfony\Bundle\FrameworkBundle\Test\WebTestCase;
use Symfony\Component\Console\Tester\CommandTester;

use function array_diff_assoc;
use function array_keys;
use function count;
use function file_get_contents;
use function implode;
use function is_array;
use function json_decode;
use function sprintf;
use function str_contains;

use const JSON_THROW_ON_ERROR;

/**
 * Host shapes in a real kernel (1.19.0; since 2.0 the private manager and the framework-free ports are the only modes):
 * `lint:container` passes for every shape (the host's ports, the built-ins, a DDD host with the id mapping and the XML
 * mapping), every gate is wired, and every shape answers every page, list, share page and reveal exactly as v1.21.2
 * did with the 1.18 wiring of the same host (status codes, deny_status, which items each list shows). The v1.21.2
 * answers are recorded in tests/Fixtures/ports-1.21.2-decisions.json (generated by the v1.21.2 PortsKernelTest
 * reference variants): removing the deprecated ports and the 1.18 persistence in 2.0 changed no decision.
 */
final class PortsKernelTest extends WebTestCase
{
    use VariantKernelSupport;

    private const BASELINES = __DIR__ . '/../../Fixtures/ports-1.21.2-decisions.json';

    protected static function getKernelClass(): string
    {
        return VariantKernel::class;
    }

    /**
     * @return iterable<string, array{string, string}>
     */
    public static function variants(): iterable
    {
        yield 'host ports' => ['private_relation_new', 'legacy_relation_legacy'];
        yield 'XML mapping' => ['private_relxml_new', 'legacy_relation_legacy'];
        yield 'built-ins' => ['private_relation_builtin', 'legacy_relation_builtin'];
        yield 'deny_status 404' => ['private_relation_new_404', 'legacy_relation_legacy_404'];
        yield 'id mapping' => ['private_id_new', 'legacy_id_legacy'];
        yield 'DDD host: id + XML mapping' => ['private_idxml_new', 'legacy_id_legacy'];
    }

    #[Test]
    #[DataProvider('variants')]
    public function everyHostShapeLintsAndDecidesLikeV1212(string $variant, string $reference): void
    {
        $baselines = json_decode((string) file_get_contents(self::BASELINES), true, 512, JSON_THROW_ON_ERROR);
        self::assertIsArray($baselines);
        $baseline = $baselines[$reference] ?? null;
        self::assertTrue(is_array($baseline), $reference);

        $decisions = $this->decisions($variant);

        self::assertGreaterThan(60, count($baseline));
        self::assertSame([], array_diff_assoc($baseline, $decisions), sprintf('%s differs from v1.21.2 %s: %s', $variant, $reference, implode(', ', array_keys(array_diff_assoc($baseline, $decisions)))));
        self::assertSame($baseline, $decisions);
    }

    /**
     * Boots the variant, lints its container, seeds the same rows and returns its decisions.
     *
     * @return array<string, string>
     */
    private function decisions(string $variant): array
    {
        self::ensureKernelShutdown();
        $client = self::createClient(['environment' => $variant, 'debug' => true]);
        $client->disableReboot();

        $application = new Application(self::$kernel);
        $application->setAutoExit(false);
        $tester = new CommandTester($application->find('lint:container'));
        self::assertSame(0, $tester->execute([]), $variant . ': ' . $tester->getDisplay());

        $container = self::getContainer();
        foreach (['access_checker', 'team_membership', 'scope_access', 'user_locator', 'health_reporter'] as $port) {
            self::assertTrue($container->has(VaultPortsPass::GATE_PREFIX . $port) || $container->hasParameter(VaultPortsPass::PARAMETER_PREFIX . $port . '.service'), $variant . ': ' . $port);
        }
        self::resetSchema($container);
        $users = self::seedUsers($container, str_contains($variant, '_id'));
        $ids   = self::seedVault($container, $users);

        return self::requestMatrix($client, $users, $ids);
    }
}
