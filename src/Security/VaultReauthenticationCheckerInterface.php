<?php

declare(strict_types=1);

namespace Nowo\VaultBundle\Security;

use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\Security\Core\User\UserInterface;

/**
 * Host hook for a fresh re-authentication (1.16.0, contract §9.1), required by the decrypted personal export. There is
 * no default implementation: `export.enabled` without `export.reauth_checker` fails the container compile.
 *
 * Host obligations (the bundle cannot verify them): `factors` lists only factors verified in the re-auth step (never at
 * login, never through remember-me or an SSO session reuse); `mfaEnrolled` is read from the store; the re-auth page is
 * CSRF-protected and rate-limited and regenerates the session id before recording the session binding; `returnTo` is
 * followed only when it is a same-origin path.
 */
interface VaultReauthenticationCheckerInterface
{
    /**
     * The freshest interactive re-authentication of $user in this session for $purpose, or null.
     */
    public function getProof(UserInterface $user, Request $request, string $purpose): ?VaultReauthProof;

    /**
     * Marks the proof used. A consumed proof is never returned again by getProof().
     */
    public function consume(VaultReauthProof $proof): void;

    /**
     * Where to re-authenticate. $returnTo is a same-origin path generated by the bundle.
     */
    public function getReauthenticationUrl(Request $request, string $purpose, string $returnTo): string;
}
